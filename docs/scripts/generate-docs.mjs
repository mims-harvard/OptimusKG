import { execSync } from "node:child_process";
import * as fs from "node:fs/promises";
import { existsSync, mkdtempSync } from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import * as Python from "fumadocs-python";

const DOCS_DIR = path.resolve(import.meta.dirname, "..");
const CLIENT_PKG = path.resolve(DOCS_DIR, "../packages/optimuskg");
const FUMAPY_PKG = path.resolve(DOCS_DIR, "node_modules/fumadocs-python");
const OUT_DIR = path.resolve(DOCS_DIR, "content/docs/optimuskg-client");
const BASE_URL = "/docs/optimuskg-client/reference";

function isPrivate(name) {
  return (
    name.startsWith("_") && !(name.startsWith("__") && name.endsWith("__"))
  );
}

function filterPrivate(container, keys) {
  for (const key of keys) {
    for (const name of Object.keys(container[key] ?? {})) {
      if (isPrivate(name)) delete container[key][name];
    }
  }
}

function rebasePath(item, oldPrefix, newPrefix) {
  item.path = item.path.replace(oldPrefix, newPrefix);
  for (const sub of Object.values(item.functions ?? {}))
    rebasePath(sub, oldPrefix, newPrefix);
  for (const sub of Object.values(item.classes ?? {}))
    rebasePath(sub, oldPrefix, newPrefix);
  for (const sub of Object.values(item.modules ?? {}))
    rebasePath(sub, oldPrefix, newPrefix);
}

function promoteSubmodule(root, subName) {
  const sub = root.modules?.[subName];
  if (!sub) return;
  const oldPrefix = `${root.path}.${subName}`;
  for (const [name, fn] of Object.entries(sub.functions ?? {})) {
    if (isPrivate(name)) continue;
    rebasePath(fn, oldPrefix, root.path);
    root.functions[name] = fn;
  }
  for (const [name, cls] of Object.entries(sub.classes ?? {})) {
    if (isPrivate(name)) continue;
    rebasePath(cls, oldPrefix, root.path);
    root.classes[name] = cls;
  }
  for (const attr of sub.attributes ?? []) {
    if (isPrivate(attr.name)) continue;
    root.attributes.push(attr);
  }
  delete root.modules[subName];
}

function flatten(mod) {
  mod.modules ??= {};
  mod.classes ??= {};
  mod.functions ??= {};
  mod.attributes ??= [];
  // Promote re-exported modules so the top-level `optimuskg` module documents
  // the public API directly rather than pointing at internal submodules.
  promoteSubmodule(mod, "api");
  promoteSubmodule(mod, "_config");
  // Drop remaining private submodules and private members.
  for (const name of Object.keys(mod.modules)) {
    if (isPrivate(name)) delete mod.modules[name];
  }
  filterPrivate(mod, ["classes", "functions"]);
  mod.attributes = mod.attributes.filter((a) => !isPrivate(a.name));
  for (const sub of Object.values(mod.modules)) flatten(sub);
}

async function ensureJson() {
  const tmpDir = mkdtempSync(path.join(os.tmpdir(), "fumapy-"));
  execSync(
    `uvx --from "${FUMAPY_PKG}" --with "${CLIENT_PKG}" fumapy-generate optimuskg --dir "${tmpDir}"`,
    { stdio: "inherit" }
  );
  const jsonPath = path.join(tmpDir, "optimuskg.json");
  if (!existsSync(jsonPath)) {
    throw new Error(`fumapy-generate did not produce ${jsonPath}`);
  }
  return jsonPath;
}

async function generate() {
  const jsonPath = await ensureJson();
  const content = JSON.parse(await fs.readFile(jsonPath, "utf8"));
  flatten(content);

  const converted = Python.convert(content, { baseUrl: BASE_URL });
  await fs.mkdir(OUT_DIR, { recursive: true });

  // The converter emits the top-level module as `optimuskg/index.mdx` and any
  // submodules as `optimuskg/<sub>/index.mdx`. Write the top module as
  // `reference.mdx` so it sits beside the hand-written `index.mdx`
  // introduction; pass any submodules through untouched.
  await Promise.all(
    converted.map(async (file) => {
      const relative = file.path.split("/").slice(1).join("/");
      const isTopIndex = relative === "index.mdx";
      const destRelative = isTopIndex ? "reference.mdx" : relative;
      const destPath = path.join(OUT_DIR, destRelative);
      const fm = isTopIndex
        ? {
            title: "Reference",
            description:
              "Autogenerated API reference for the optimuskg Python client.",
          }
        : file.frontmatter;
      await fs.mkdir(path.dirname(destPath), { recursive: true });
      await fs.writeFile(
        destPath,
        `${Python.frontmatter(fm)}\n\n${file.content}`
      );
    })
  );
}

await generate();
